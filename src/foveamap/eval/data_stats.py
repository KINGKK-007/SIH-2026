"""Data statistics per distance bucket (PHASES T4.2): the sample sizes behind every far-range metric.

Per sequence and bucket (L16): points, points per super-class, moving and safety-critical points, and
object instances (unique ``(raw class, instance id)`` per frame, bucketed by centroid range) split into
static vehicles, moving vehicles and persons/cyclists. Frames are subsampled with ``stride`` (stated in
the output).
"""

from __future__ import annotations

from collections.abc import Sequence as SeqType
from pathlib import Path
from typing import Any

import numpy as np

from foveamap.eval.buckets import DEFAULT_EDGES_M, bucket_labels, bucket_of_range, horizontal_range
from foveamap.io.kitti import split_label
from foveamap.io.labels import SUPER_CLASS_NAMES, is_safety_critical, raw_to_super
from foveamap.io.sequence import Sequence

VEHICLE_RAW = (10, 11, 13, 15, 16, 18, 20)
MOVING_VEHICLE_RAW = (252, 256, 257, 258, 259)
PERSON_RAW = (30, 31, 32, 253, 254, 255)
OBJECT_GROUPS = {
    "vehicle_static": VEHICLE_RAW,
    "vehicle_moving": MOVING_VEHICLE_RAW,
    "person_cyclist": PERSON_RAW,
}


def _object_buckets(xyz: np.ndarray, raw: np.ndarray, edges: SeqType[float]) -> dict[str, np.ndarray]:
    sem, inst = split_label(raw)
    n_buckets = len(edges) - 1
    counts = {g: np.zeros(n_buckets, dtype=np.int64) for g in OBJECT_GROUPS}
    thing = inst > 0
    if not thing.any():
        return counts
    keys = sem[thing].astype(np.int64) << 16 | inst[thing].astype(np.int64)
    uniq, inverse = np.unique(keys, return_inverse=True)
    pts = xyz[thing].astype(np.float64)
    n = np.bincount(inverse)
    cx = np.bincount(inverse, weights=pts[:, 0]) / n
    cy = np.bincount(inverse, weights=pts[:, 1]) / n
    b = bucket_of_range(np.hypot(cx, cy), edges)
    cls = (uniq >> 16).astype(np.int64)
    for group, ids in OBJECT_GROUPS.items():
        sel = np.isin(cls, ids) & (b >= 0)
        counts[group] += np.bincount(b[sel].astype(np.intp), minlength=n_buckets)
    return counts


def sequence_stats(seq: Sequence, edges: SeqType[float] = DEFAULT_EDGES_M) -> dict[str, Any]:
    n_buckets = len(edges) - 1
    points = np.zeros(n_buckets, dtype=np.int64)
    beyond = 0
    per_super = np.zeros((len(SUPER_CLASS_NAMES), n_buckets), dtype=np.int64)
    moving = np.zeros(n_buckets, dtype=np.int64)
    safety = np.zeros(n_buckets, dtype=np.int64)
    objects = {g: np.zeros(n_buckets, dtype=np.int64) for g in OBJECT_GROUPS}
    n_frames = 0
    for scan in seq:
        if scan.raw_labels is None:
            raise ValueError("data statistics need labels")
        n_frames += 1
        b = bucket_of_range(horizontal_range(scan.xyz), edges)
        inside = b >= 0
        beyond += int((~inside).sum())
        bi = b[inside].astype(np.intp)
        points += np.bincount(bi, minlength=n_buckets)
        supers, mov = raw_to_super(scan.raw_labels)
        flat = supers[inside].astype(np.intp) * n_buckets + bi
        per_super += np.bincount(flat, minlength=per_super.size).reshape(per_super.shape)
        moving += np.bincount(bi[mov[inside]], minlength=n_buckets)
        safety += np.bincount(bi[is_safety_critical(scan.raw_labels)[inside]], minlength=n_buckets)
        for group, counts in _object_buckets(scan.xyz, scan.raw_labels, edges).items():
            objects[group] += counts
    return {
        "sequence": seq.seq,
        "frames_used": n_frames,
        "frame_stride": seq.frame_stride,
        "points": points.tolist(),
        "points_beyond_last_bucket": beyond,
        "super_class_points": {name: per_super[k].tolist() for k, name in enumerate(SUPER_CLASS_NAMES)},
        "moving_points": moving.tolist(),
        "safety_critical_points": safety.tolist(),
        "object_instances": {g: c.tolist() for g, c in objects.items()},
    }


def data_stats(
    root: str | Path, sequences: SeqType[str], stride: int = 1, edges: SeqType[float] = DEFAULT_EDGES_M
) -> dict[str, Any]:
    return {
        "experiment": "data_stats",
        "buckets_m": list(edges),
        "bucket_labels": bucket_labels(edges),
        "note": "object instances are counted once per frame they appear in (bucketed by centroid range)",
        "sequences": [sequence_stats(Sequence(root, s, frame_stride=stride), edges) for s in sequences],
    }


def stats_table_md(stats: dict[str, Any]) -> str:
    """Markdown tables (one per sequence) for ``results/tables/data_stats.md``; generated only."""
    labels = stats["bucket_labels"]
    out = [
        "# Data statistics per distance bucket",
        "",
        "Generated by `foveamap stats` (PHASES T4.2). Do not edit by hand (R1).",
        f"Buckets: horizontal range, {', '.join(labels)}; points beyond the last edge are listed separately.",
        f"{stats['note']}.",
    ]
    header = "| | " + " | ".join(labels) + " |"
    rule = "|---|" + "---:|" * len(labels)
    for s in stats["sequences"]:
        out += [
            "",
            f"## Sequence {s['sequence']} ({s['frames_used']} frames, stride {s['frame_stride']})",
            "",
        ]
        out += [header, rule]

        def row(name: str, values: list[int]) -> str:
            return f"| {name} | " + " | ".join(f"{v:,}" for v in values) + " |"

        out.append(row("points", s["points"]))
        for name, values in s["super_class_points"].items():
            out.append(row(f"  {name}", values))
        out.append(row("moving points", s["moving_points"]))
        out.append(row("safety-critical points", s["safety_critical_points"]))
        for group, values in s["object_instances"].items():
            out.append(row(f"objects: {group}", values))
        out.append("")
        out.append(f"Points beyond {stats['buckets_m'][-1]:g} m: {s['points_beyond_last_bucket']:,}")
    return "\n".join(out) + "\n"
